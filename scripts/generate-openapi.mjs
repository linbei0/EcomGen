function normalizePathSchemas(pathsDocument) {
  const paths = structuredClone(pathsDocument.paths ?? {});
  for (const pathItem of Object.values(paths)) {
    for (const operation of Object.values(pathItem ?? {})) {
      if (!operation || typeof operation !== "object" || !operation.operationId) continue;
      const mapping = operationSchemaRefs[operation.operationId];
      if (!mapping) continue;
      if (mapping.request && operation.requestBody?.content) {
        for (const media of Object.values(operation.requestBody.content)) media.schema = { $ref: `#/components/schemas/${mapping.request}` };
      }
      for (const [status, name] of Object.entries(mapping.response ?? {})) {
        const response = operation.responses?.[status];
        if (!response?.content) continue;
        for (const media of Object.values(response.content)) media.schema = { $ref: `#/components/schemas/${name}` };
      }
    }
  }
  return { paths };
}

mkdirSync(outputDir, { recursive: true });
const existing = parse(readFileSync(openapiRoot, "utf8"));
if (!check && !existsSync(join(outputDir, "paths.yaml"))) writeFileSync(join(outputDir, "paths.yaml"), dump({ paths: existing.paths }), "utf8");
if (!check && !existsSync(join(outputDir, "components.yaml"))) writeFileSync(join(outputDir, "components.yaml"), dump({ components: { parameters: existing.components?.parameters ?? {}, responses: existing.components?.responses ?? {} } }), "utf8");

const { API_SCHEMA_REGISTRY } = await import("../packages/contracts/dist/api-registry.js");
const schemas = {};
for (const [name, schema] of Object.entries(API_SCHEMA_REGISTRY)) schemas[name] = stableSchema(schema);
writeOrCheck(join(outputDir, "schemas.generated.yaml"), dumpGenerated({ components: { schemas } }));

const pathsSource = normalizePathSchemas(parse(readFileSync(join(outputDir, "paths.yaml"), "utf8")));
writeOrCheck(join(outputDir, "paths.yaml"), dump(pathsSource));
const componentsSource = parse(readFileSync(join(outputDir, "components.yaml"), "utf8"));
const bundled = {
  openapi: existing.openapi,
  info: existing.info,
  security: existing.security ?? [],
  servers: existing.servers ?? [],
  paths: pathsSource.paths,
  components: { ...(componentsSource.components ?? {}), schemas },
};
writeOrCheck(openapiRoot, dumpGenerated(bundled));

if (check) {
  const temp = mkdtempSync(join(tmpdir(), "ecomgen-contract-")).replaceAll("\\", "/");
  try {
    const generated = join(temp, "schema.d.ts");
    const result = spawnSync("pnpm", ["--filter", "@ecomgen/web", "exec", "openapi-typescript", "../../openapi.yaml", "-o", generated], { cwd: root, stdio: "inherit", shell: true });
    if (result.status !== 0) process.exitCode = result.status ?? 1;
    else if (readFileSync(generated, "utf8") !== readFileSync(join(root, "apps/web/src/api/schema.d.ts"), "utf8")) {
      console.error("Generated Web API types are stale: apps/web/src/api/schema.d.ts");
      process.exitCode = 1;
    }
  } finally { rmSync(temp, { recursive: true, force: true }); }
}

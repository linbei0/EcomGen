  confirmStoryboard: { request: "ConfirmStoryboardInput" },
  createGenerationJobs: { request: "CreateGenerationJobInput", response: { "202": "GenerationJobsResponse" } },
  updateEditSessionMemory: { request: "UpdateEditSessionMemoryInput" },
  listEditReferenceAssets: { response: { "200": "EditReferenceAssetList" } },

  createEditTurn: { request: "CreateEditTurnInput", response: { "202": "EditTurnQueuedResponse" } },
  selectEditSessionOutput: { request: "SelectEditSessionOutputInput" },
  approveEditTurn: { response: { "202": "ApproveEditTurnResponse" } },
